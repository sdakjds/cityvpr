# 路线颜色（11条路线各不同）
ROUTE_COLORS = [
    "#E53935", "#D81B60", "#8E24AA", "#5E35B1", "#3949AB",
    "#1E88E5", "#00ACC1", "#00897B", "#43A047", "#7CB342",
    "#FB8C00",
]


def calc_distance(route):
    d = 0.0
    for i in range(1, len(route)):
        x1, z1 = WAYPOINTS[route[i-1]]
        x2, z2 = WAYPOINTS[route[i]]
        d += math.sqrt((x2-x1)**2 + (z2-z1)**2)
    return round(d, 2)


def generate_route_svg(buildings, route_idx):
    """生成单条路线的 SVG"""
    route = ROUTES[route_idx]
    route_color = ROUTE_COLORS[route_idx % len(ROUTE_COLORS)]
    route_name = "route{}".format(route_idx + 1)

    margin = 40
    cell_size = 8
    grid_w = 100
    grid_h = 100
    z_start = 50

    svg_w = grid_w * cell_size + margin * 2
    svg_h = grid_h * cell_size + margin * 2 + 100

    parts = []
    p = parts.append

    p('<?xml version="1.0" encoding="UTF-8"?>')
    p('<!DOCTYPE svg PUBLIC "-//W3C//DTD SVG 1.1//EN" "http://www.w3.org/Graphics/SVG/1.1/DTD/svg11.dtd">')
    p('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {} {}" width="90%" style="position: absolute; top: 50%; left: 50%; transform: translate(-50%, -50%); max-height: 95vh;">'.format(
        svg_w, svg_h))
    p('<style>')
    p('  svg { background: #fafafa; }')
    p('  .road { fill: #ddd; }')
    p('  .grass { fill: #f9f9f9; }')
    p('  .building { stroke: #bbb; stroke-width: 0.5; }')
    p('  .building-label { font: 7px Arial; fill: #999; text-anchor: middle; dominant-baseline: middle; }')
    p('  .route-line { stroke: ' + route_color + '; stroke-width: 3.5; fill: none; stroke-linecap: round; stroke-linejoin: round; opacity: 0.85; }')
    p('  .route-arrow { fill: ' + route_color + '; opacity: 0.8; }')
    p('  .wp-on-route { fill: ' + route_color + '; stroke: #fff; stroke-width: 2; }')
    p('  .wp-off-route { fill: #ccc; stroke: #999; stroke-width: 1; }')
    p('  .wp-label-on { font: bold 9px Arial; fill: ' + route_color + '; text-anchor: middle; }')
    p('  .wp-label-off { font: 7px Arial; fill: #aaa; text-anchor: middle; }')
    p('  .title { font: bold 18px Arial; fill: #333; text-anchor: middle; }')
    p('  .legend-text { font: 14px Arial; fill: #333; }')
    p('  .axis-label { font: 10px Arial; fill: #666; }')
    p('  .start-marker { fill: #00C853; stroke: #fff; stroke-width: 2; }')
    p('  .end-marker { fill: #D50000; stroke: #fff; stroke-width: 2; }')
    p('</style>')

    # 背景
    p('<rect x="{}" y="{}" width="{}" height="{}" class="grass"/>'.format(
        margin, margin, grid_w * cell_size, grid_h * cell_size))

    # 画道路（淡色）
    for gz in range(grid_h):
        row = ROAD_GRID[gz] if gz < len(ROAD_GRID) else ""
        for gx in range(grid_w):
            if gx < len(row) and row[gx] == '1':
                px = margin + gx * cell_size
                py = margin + gz * cell_size
                p('<rect x="{}" y="{}" width="{}" height="{}" class="road"/>'.format(
                    px, py, cell_size, cell_size))

    # 画建筑（淡色）
    for i, b in enumerate(buildings):
        if 'corner_nw' in b:
            nw = b['corner_nw']
            se = b['corner_se']
            x1 = margin + nw['x'] * cell_size
            y1 = margin + (nw['z'] - z_start) * cell_size
            bw = (se['x'] - nw['x']) * cell_size
            bh = (se['z'] - nw['z']) * cell_size
        else:
            gx = b['grid_x']
            gz = b['grid_z']
            x1 = margin + gx * cell_size
            y1 = margin + (gz - z_start) * cell_size
            bw = b['width_blocks'] * cell_size
            bh = b['depth_blocks'] * cell_size

        p('<rect x="{:.1f}" y="{:.1f}" width="{:.1f}" height="{:.1f}" class="building" fill="#e0e0e0"/>'.format(
            x1, y1, bw, bh))

        cx = x1 + bw / 2
        cy = y1 + bh / 2
        if bw >= 30 and bh >= 20:
            p('<text x="{:.1f}" y="{:.1f}" class="building-label">{}</text>'.format(
                cx, cy, b['building_id']))

    # 画非路线上的路径点（灰色）
    route_set = set(route)
    for i, (wx, wz) in enumerate(WAYPOINTS):
        if i not in route_set:
            px = margin + (wx + 0.5) * cell_size
            py = margin + (wz - z_start + 0.5) * cell_size
            p('<circle cx="{:.1f}" cy="{:.1f}" r="3" class="wp-off-route"/>'.format(px, py))

    # 画路线连线
    path_points = []
    for wp_idx in route:
        wx, wz = WAYPOINTS[wp_idx]
        px = margin + (wx + 0.5) * cell_size
        py = margin + (wz - z_start + 0.5) * cell_size
        path_points.append((px, py))

    # 路线折线
    path_d = " ".join("{:.1f},{:.1f}".format(x, y) for x, y in path_points)
    p('<polyline points="{}" class="route-line"/>'.format(path_d))

    # 画方向箭头（每段中点）
    for i in range(1, len(path_points)):
        x1, y1 = path_points[i-1]
        x2, y2 = path_points[i]
        mx = (x1 + x2) / 2
        my = (y1 + y2) / 2
        dx = x2 - x1
        dy = y2 - y1
        length = math.sqrt(dx*dx + dy*dy)
        if length < 5:
            continue
        ux = dx / length
        uy = dy / length
        arrow_size = 5
        ax1 = mx - uy * arrow_size - ux * arrow_size * 0.5
        ay1 = my + ux * arrow_size - uy * arrow_size * 0.5
        ax2 = mx + uy * arrow_size - ux * arrow_size * 0.5
        ay2 = my - ux * arrow_size - uy * arrow_size * 0.5
        p('<polygon points="{:.1f},{:.1f} {:.1f},{:.1f} {:.1f},{:.1f}" class="route-arrow"/>'.format(
            mx + ux * arrow_size, my + uy * arrow_size, ax1, ay1, ax2, ay2))

    # 画路线上的路径点（高亮）
    for idx, wp_idx in enumerate(route):
        wx, wz = WAYPOINTS[wp_idx]
        px = margin + (wx + 0.5) * cell_size
        py = margin + (wz - z_start + 0.5) * cell_size

        if idx == 0:
            # 起点（绿色）
            p('<circle cx="{:.1f}" cy="{:.1f}" r="6" class="start-marker"/>'.format(px, py))
            p('<text x="{:.1f}" y="{:.1f}" class="wp-label-on" font-size="8px">W{}</text>'.format(
                px, py - 10, wp_idx))
        elif idx == len(route) - 1:
            # 终点（红色）
            p('<circle cx="{:.1f}" cy="{:.1f}" r="6" class="end-marker"/>'.format(px, py))
            p('<text x="{:.1f}" y="{:.1f}" class="wp-label-on" font-size="8px">W{}</text>'.format(
                px, py - 10, wp_idx))
        else:
            # 中间点
            p('<circle cx="{:.1f}" cy="{:.1f}" r="5" class="wp-on-route"/>'.format(px, py))
            p('<text x="{:.1f}" y="{:.1f}" class="wp-label-on" font-size="8px">W{}</text>'.format(
                px, py - 9, wp_idx))

    # 标题
    dist = calc_distance(route)
    p('<text x="{}" y="25" class="title">{} (W{}~W{}, {} waypoints, {:.1f}m)</text>'.format(
        svg_w / 2, route_name, route[0], route[-1], len(route), dist))

    # 坐标标注
    p('<text x="{}" y="{}" class="axis-label">(0, 50)</text>'.format(margin - 5, margin - 5))
    p('<text x="{}" y="{}" class="axis-label" text-anchor="end">(99, 50)</text>'.format(
        margin + grid_w * cell_size + 5, margin - 5))
    p('<text x="{}" y="{}" class="axis-label">(0, 149)</text>'.format(
        margin - 5, margin + grid_h * cell_size + 12))
    p('<text x="{}" y="{}" class="axis-label" text-anchor="end">(99, 149)</text>'.format(
        margin + grid_w * cell_size + 5, margin + grid_h * cell_size + 12))

    # 图例
    legend_y = margin + grid_h * cell_size + 45
    legend_start_x = margin + 20

    p('<line x1="{}" y1="{}" x2="{}" y2="{}" stroke="{}" stroke-width="3.5" stroke-linecap="round"/>'.format(
        legend_start_x, legend_y + 8, legend_start_x + 30, legend_y + 8, route_color))
    p('<text x="{}" y="{}" class="legend-text">{} Path</text>'.format(
        legend_start_x + 38, legend_y + 13, route_name))

    p('<circle cx="{}" cy="{}" r="6" class="start-marker"/>'.format(legend_start_x + 130, legend_y + 8))
    p('<text x="{}" y="{}" class="legend-text">Start</text>'.format(
        legend_start_x + 142, legend_y + 13))

    p('<circle cx="{}" cy="{}" r="6" class="end-marker"/>'.format(legend_start_x + 210, legend_y + 8))
    p('<text x="{}" y="{}" class="legend-text">End</text>'.format(
        legend_start_x + 222, legend_y + 13))

    p('<circle cx="{}" cy="{}" r="5" class="wp-on-route"/>'.format(legend_start_x + 290, legend_y + 8))
    p('<text x="{}" y="{}" class="legend-text">Waypoint</text>'.format(
        legend_start_x + 302, legend_y + 13))

    # 指南针
    compass_cx = margin + grid_w * cell_size + margin / 2
    compass_cy = margin + 25
    compass_r = 25
    p('<circle cx="{}" cy="{}" r="{}" fill="#fff" stroke="#999" stroke-width="1.5"/>'.format(
        compass_cx, compass_cy, compass_r))
    p('<polygon points="{cx},{ny} {cxl},{cy} {cxr},{cy}" fill="#d32f2f"/>'.format(
        cx=compass_cx, ny=compass_cy - 7,
        cxl=compass_cx - 6, cxr=compass_cx + 6, cy=compass_cy))
    p('<polygon points="{cx},{sy} {cxl},{cy} {cxr},{cy}" fill="#888"/>'.format(
        cx=compass_cx, sy=compass_cy + 7,
        cxl=compass_cx - 6, cxr=compass_cx + 6, cy=compass_cy))
    p('<text x="{}" y="{}" class="legend-text" text-anchor="middle" font-weight="bold" fill="#d32f2f" font-size="13">N</text>'.format(
        compass_cx, compass_cy - compass_r + 10))
    p('<text x="{}" y="{}" class="legend-text" text-anchor="middle" font-size="12">S</text>'.format(
        compass_cx, compass_cy + compass_r - 4))
    p('<text x="{}" y="{}" class="legend-text" text-anchor="middle" font-size="12">W</text>'.format(
        compass_cx - compass_r + 9, compass_cy + 4))
    p('<text x="{}" y="{}" class="legend-text" text-anchor="middle" font-size="12">E</text>'.format(
        compass_cx + compass_r - 9, compass_cy + 4))

    p('</svg>')
    return "\n".join(parts)


def main():
    if len(sys.argv) < 2:
        print("用法: py -3.6 generate_route_maps.py \"数据集目录路径\"")
        sys.exit(1)

    dataset_root = sys.argv[1]
    if not os.path.isdir(dataset_root):
        print("错误: 目录不存在 - " + dataset_root)
        sys.exit(1)

    print("=" * 60)
    print("生成 11 张路线图 SVG")
    print("=" * 60)

    # 加载建筑数据
    buildings_path = os.path.join(dataset_root, "buildings.json")
    if not os.path.exists(buildings_path):
        print("[错误] 未找到 buildings.json")
        sys.exit(1)

    with open(buildings_path, 'r', encoding='utf-8') as f:
        buildings = json.load(f)

    print("  建筑数量: {}".format(len(buildings)))

    # 创建输出目录
    output_dir = os.path.join(dataset_root, "route_maps")
    if not os.path.exists(output_dir):
        os.makedirs(output_dir)

    # 生成 11 张路线图
    for i in range(len(ROUTES)):
        svg_content = generate_route_svg(buildings, i)
        output_path = os.path.join(output_dir, "route{}.svg".format(i + 1))
        with open(output_path, 'w', encoding='utf-8') as f:
            f.write(svg_content)

        route = ROUTES[i]
        dist = calc_distance(route)
        print("  route{}.svg: W{}->W{} ({} waypoints, {:.1f}m)".format(
            i + 1, route[0], route[-1], len(route), dist))

    print("\n  输出目录: " + output_dir)
    print("  共生成 {} 张路线图".format(len(ROUTES)))
    print("=" * 60)


if __name__ == "__main__":
    main()
